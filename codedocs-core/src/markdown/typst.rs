//! Markdown → Typst markup, for the PDF export.
//!
//! The output is Typst *source*, plain text, which the Typst CLI compiles to a
//! PDF. It is not HTML and not a PDF library API: keeping the compilation in a
//! subprocess is what stops a PDF engine from becoming a dependency of the app.
//!
//! # Why the output is safe
//!
//! This looks like the HTML renderer's threat model turned up again —
//! untrusted markdown reaching a compiler — and it is the same argument with a
//! different consequence. The output is a language *we generate in full*: there
//! is no template where document text lands as markup. Everything from the
//! document goes through [`escape_text`], which backslash-escapes every
//! character Typst gives meaning to, so a `$` in prose stays a `$` and cannot
//! open math, a `#` cannot start a code expression, and a `` ` `` cannot open a
//! raw block.
//!
//! That property is why no document text is ever placed inside a Typst string
//! literal passed to `#raw`/`#link`/`#image`. It would need its own escaping,
//! and one mistake there is not a rendering bug: Typst source can read files
//! (`#read`), so a breakout would be a sandbox escape rather than a typo. Code
//! spans and blocks are emitted as backtick *fences* instead, where the content
//! is literal by construction. The only strings in the output are URLs, which
//! go through the same scheme check the HTML renderer uses.
//!
//! # What Typst actually accepts
//!
//! The mapping is not "markdown in, Typst out" by intuition; every construct
//! below was compiled with the real CLI (0.15.1) before being written down. Two
//! surprises are worth keeping in mind:
//!
//! * A bare `$` in prose breaks the *whole document*, not just its paragraph:
//!   `$5 y $10` is an unclosed math delimiter and `typst compile` fails. Hence
//!   the escape set.
//! * Typst has no syntax for `- [ ]`, so task lists are drawn by hand with
//!   [`checkbox`]; passing `- [ ]` through emits those characters literally.

