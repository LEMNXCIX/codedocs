/// Page setup emitted before the document.
///
/// Deliberately no `font:`: an unavailable font name fails the compilation, and
/// the CLI's defaults (Libertinus Serif, plus the math and mono faces it
/// embeds) already look like a document.
const PREAMBLE: &str = "\
// Generated by CodeDocs from a Markdown note. Edit the note, not this file.
#set page(paper: \"a4\", margin: 2.5cm)
#set text(size: 11pt)
#set par(justify: true)
";

/// Render markdown as Typst markup.
///
/// The result is a complete `.typ` document: [`PREAMBLE`] plus the body.
/// Compiling it is the caller's job (the `export_pdf` command), which keeps
/// this function pure and testable without a Typst binary around.
pub fn markdown_to_typst(content: &str) -> String {
    let events: Vec<Event<'_>> = Parser::new_ext(content, parser_options()).collect();
    // Two passes over the parsed events. The first renders the footnote
    // definitions, because in markdown a *reference* almost always comes first
    // — `#footnote[…]` is emitted at the reference site, so the body has to be
    // known before the body that refers to it starts.
    let footnotes = collect_footnotes(&events);
    let mut writer = Writer {
        link_stack: Vec::new(),
        suppress_image_text: 0,
        footnotes,
        in_footnote: false,
        depth: 0,
        quote_depth: 0,
    };
    let mut body = String::new();
    writer.blocks(&events, &mut body);
    format!("{PREAMBLE}\n{}", body.trim_matches('\n'))
}

/// The Typst spelling of one task-list marker.
///
/// Drawn with Typst primitives rather than with a character: U+2610 and U+2713
/// are in none of the faces the CLI embeds, so a literal `☐` renders as a blank
/// box — checked against the real compiler, rendering the page to an image. The
/// check mark is a `curve`, so it needs no font either.
fn checkbox(checked: bool) -> &'static str {
    const UNCHECKED: &str = "#box(stroke: 0.5pt, width: 0.75em, height: 0.75em, inset: 0pt)[]";
    const CHECKED: &str = concat!(
        "#box(stroke: 0.5pt, width: 0.9em, height: 0.9em, inset: 0pt)[",
        "#align(left + top)[",
        "#curve(curve.move((0.14em, 0.32em)), curve.line((0.34em, 0.58em)), ",
        "curve.line((0.70em, 0.10em)), stroke: 0.9pt)",
        "]",
        "]",
    );
    if checked {
        CHECKED
    } else {
        UNCHECKED
    }
}

/// Characters escaped before any document text reaches the output.
///
/// Every character Typst's markup gives a meaning to. Escaping unconditionally
/// — rather than only where a character happens to sit at the start of a line —
/// is what makes the output a function of the document instead of of its
/// context: `=`, `-`, `+` and `/` become heading and list markers only at the
/// start of a line, and where a line starts is not something this module always
/// knows, because a soft break inside a paragraph can produce one.
///
/// The set was verified against the real compiler: each of these escapes is
/// accepted and produces the bare character. `.` is deliberately absent, it
/// carries no meaning in markup (`...` becoming an ellipsis is cosmetic).
fn escape_text(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for ch in text.chars() {
        if matches!(
            ch,
            '\\' | '`'
                | '*'
                | '_'
                | '$'
                | '#'
                | '@'
                | '<'
                | '>'
                | '['
                | ']'
                | '~'
                | '-'
                | '+'
                | '='
                | '/'
                | '\''
                | '"'
                | '{'
                | '}'
        ) {
            out.push('\\');
        }
        out.push(ch);
    }
    out
}

/// Document text inside a Typst string literal.
///
/// The one place a string is unavoidable — a URL has to be one — and the reason
/// the escaping above is not enough on its own: a `\` or a `"` in the value
/// would otherwise close the literal and turn the rest of the URL into code.
/// Escaping both is total, since every character that can end a string literal
/// is escaped and no byte of the value can escape from inside it.
fn quote_string(value: &str) -> String {
    let mut out = String::with_capacity(value.len() + 2);
    out.push('"');
    for ch in value.chars() {
        if ch == '\\' || ch == '"' {
            out.push('\\');
        }
        out.push(ch);
    }
    out.push('"');
    out
}

/// Longest run of backticks in `text`.
fn longest_backtick_run(text: &str) -> usize {
    let mut longest = 0;
    let mut current = 0;
    for ch in text.chars() {
        if ch == '`' {
            current += 1;
            longest = longest.max(current);
        } else {
            current = 0;
        }
    }
    longest
}

/// A backtick fence long enough to contain `content`.
///
/// Typst ends a raw block at a run of backticks as long as the opening fence,
/// so code containing backticks needs a longer fence or the block closes early
/// and the rest of the code is typeset as prose.
///
/// The rule is `max(3, longest + 2)`, measured against the real compiler for
/// inner runs of 0 to 5. The two extra backticks are not superstition — each
/// weaker rule fails differently, and only one of them says so:
///
/// * `longest + 1` is wrong for a single inner backtick. `` `` `a`b` `` ``
///   compiles *successfully* and prints `ab`: the backtick silently vanishes.
/// * `longest` equal to the fence does not close the block at all — "unclosed
///   raw text", and no PDF.
///
/// The floor of three covers the other end: an inline fence shorter than three
/// does not get Typst's padded form, and the padding is what keeps the first
/// word of the code from being read as a language tag.
fn fence_for(content: &str) -> String {
    "`".repeat(fence_len(content))
}

/// How many backticks a fence for `content` needs. See [`fence_for`].
fn fence_len(content: &str) -> usize {
    (longest_backtick_run(content) + 2).max(3)
}

/// A code span, as an inline raw fence.
///
/// The single space *after* the opening fence is what stops Typst reading the
/// first word as a language tag — `` ```x``` `` swallows `x` as the tag and
/// prints nothing, and `` ```rust fn``` `` prints `fn` without `rust`. It is
/// also free: Typst consumes it as the separator between fence and content. A
/// space *before* the closing fence is not free — it stays in the output, which
/// is how `` `código `. `` came out as `código .`. Both measured by rendering
/// the page and reading the glyph positions back.
fn inline_code(code: &str) -> String {
    let fence = fence_for(code);
    format!("{fence} {code}{fence}")
}

/// The language of a fenced code block, or `None` for a plain one.
///
/// The info string is document text. It lands in Typst as a bare token, so it is
/// filtered down to what a language name can contain: a fence label such as
/// ```` ```{#x" onload="y} ```` must not become anything else. An unrecognised
/// name is harmless — Typst warns about it, it does not fail.
fn code_language(info: Option<&str>) -> Option<String> {
    let first = info?.split_whitespace().next()?;
    let name: String = first
        .chars()
        .filter(|c| c.is_ascii_alphanumeric() || matches!(c, '_' | '+' | '#' | '-' | '.'))
        .collect();
    if name.is_empty() {
        None
    } else {
        Some(name)
    }
}

/// An image path for a Typst string and for the filesystem.
///
/// Typst paths are `/`-separated on every platform, so a Windows source path is
/// normalised rather than left with separators that would have to be doubled to
/// survive the string literal.
fn image_path(dest: &str) -> String {
    dest.replace('\\', "/")
}

/// Renders an event stream into Typst markup.
struct Writer {
    /// One entry per open link: whether its destination was safe to emit. A
    /// stack, not a flag, because links nest.
    link_stack: Vec<bool>,
    /// How many images currently have their own alt text suppressed, because
    /// the image itself was emitted.
    suppress_image_text: usize,
    /// Rendered footnote bodies, by label.
    footnotes: HashMap<String, String>,
    /// Whether a footnote body is being rendered. A definition that refers to
    /// itself would otherwise recurse until the stack ran out.
    in_footnote: bool,
    /// How many list levels deep the current block sits, which is what indents a
    /// list nested inside a list item.
    depth: usize,
    /// How many block quotes deep the current block sits, which sets how far a
    /// quote's left bar is indented.
    quote_depth: usize,
}

impl Writer {
    /// Render every block in `events`, each followed by a blank line.
    ///
    /// Written as an index walk because an unmodelled event has to be able to
    /// say "skip me" without descending into it: descending into a start whose
    /// end is never found is unbounded recursion.
    fn blocks(&mut self, events: &[Event<'_>], out: &mut String) {
        let mut index = 0;
        while index < events.len() {
            index += self.block(&events[index..], out);
        }
    }

    /// Render one block, returning how many events it used.
    ///
    /// Never returns zero: an event that starts no block this module models is
    /// consumed one at a time, so an unmodelled event cannot spin the walk.
    fn block(&mut self, events: &[Event<'_>], out: &mut String) -> usize {
        let Some(first) = events.first() else {
            return 1;
        };
        let tail = &events[1..];
        match first {
            Event::Rule => {
                out.push_str("#line(length: 100%)\n\n");
                1
            }
            Event::Start(Tag::Paragraph) => {
                let (inline, used) =
                    take_until(tail, |e| matches!(e, Event::End(TagEnd::Paragraph)));
                let mut text = String::new();
                self.inline(&inline, &mut text);
                out.push_str(&text);
                out.push_str("\n\n");
                used + 2
            }
            Event::Start(Tag::Heading { level, .. }) => {
                let (inline, used) =
                    take_until(tail, |e| matches!(e, Event::End(TagEnd::Heading(_))));
                let mut text = String::new();
                self.inline(&inline, &mut text);
                let level = (*level as usize).clamp(1, 6);
                out.push_str(&"=".repeat(level));
                out.push(' ');
                out.push_str(&text);
                out.push_str("\n\n");
                used + 2
            }
            Event::Start(Tag::CodeBlock(kind)) => {
                let (inline, used) =
                    take_until(tail, |e| matches!(e, Event::End(TagEnd::CodeBlock)));
                let mut code = String::new();
                for event in &inline {
                    if let Event::Text(text) = event {
                        code.push_str(text);
                    }
                }
                self.code_block(code_language(code_info(kind)), &code, out);
                used + 2
            }
            Event::Start(Tag::BlockQuote(_)) => {
                let (inner, used) =
                    take_until(tail, |e| matches!(e, Event::End(TagEnd::BlockQuote(_))));
                let mut body = String::new();
                self.quote_depth += 1;
                // This quote's own depth, captured before it is released: the
                // first quote is 1em in, the one inside it 2em.
                let depth = self.quote_depth;
                self.blocks(&inner, &mut body);
                self.quote_depth -= 1;
                let body = body.trim_matches('\n');
                if !body.is_empty() {
                    // A `#block` with a left stroke, not a `>` on every line:
                    // Typst 0.15 typesets a leading `>` as the *character*, so a
                    // quote written that way comes out as a paragraph full of
                    // angle brackets. Verified by rendering the page.
                    out.push_str(&format!(
                        "#block(inset: (left: {depth}em), stroke: (left: 2pt), width: 100%)[{body}]\n\n"
                    ));
                }
                used + 2
            }
            Event::Start(Tag::List(start)) => {
                let (inner, used) = take_list(tail);
                self.list(start.is_some(), &inner, out, self.depth);
                used + 2
            }
            Event::Start(Tag::Table(_)) => {
                let (inner, used) = take_until(tail, |e| matches!(e, Event::End(TagEnd::Table)));
                self.table(&inner, out);
                used + 2
            }
            // The definition site of a footnote. The body was already rendered
            // into the reference, so nothing is emitted here — but the whole
            // definition is consumed, or it would be rendered twice.
            Event::Start(Tag::FootnoteDefinition(_)) => {
                let (_, used) = take_until(tail, |e| {
                    matches!(e, Event::End(TagEnd::FootnoteDefinition))
                });
                used + 2
            }
            // Raw HTML from the document: dropped, like in the HTML renderer.
            Event::Html(_) | Event::InlineHtml(_) => 1,
            Event::Start(Tag::HtmlBlock) => 1,
            // Text that reached block level means the stream held something this
            // module does not model wrapped around it. Rendering the words is
            // better than dropping them; the enclosing walk then carries on
            // through whatever else follows.
            Event::Text(text) => {
                self.text(text, out);
                out.push_str("\n\n");
                1
            }
            // Anything else: one event, unrendered. Never zero, so the walk
            // advances.
            _ => 1,
        }
    }

    /// One fenced code block.
    fn code_block(&self, language: Option<String>, code: &str, out: &mut String) {
        // The language goes *after* the opening fence, not on its own line: that
        // is Typst's info-string position, and it is what turns on syntax
        // highlighting.
        let fence = fence_for(code);
        out.push_str(&fence);
        if let Some(language) = &language {
            out.push_str(language);
        }
        out.push('\n');
        for line in code.trim_end_matches('\n').split('\n') {
            // A blank line inside the block would end it early, so empty lines
            // are emitted with the fence's indentation.
            if line.is_empty() {
                out.push_str(&" ".repeat(fence.len()));
                out.push('\n');
            } else {
                out.push_str(line);
                out.push('\n');
            }
        }
        out.push_str(&fence);
        out.push_str("\n\n");
    }

    /// A list, rendered item by item.
    ///
    /// Each item's own blocks are rendered first and then spliced in with the
    /// marker on the first line and the continuation indented to match. Doing it
    /// this way rather than tracking an indent depth as events stream past is
    /// what makes a list nested inside a list item land at the right column.
    fn list(&mut self, ordered: bool, events: &[Event<'_>], out: &mut String, depth: usize) {
        let marker = if ordered { '+' } else { '-' };
        let indent = "  ".repeat(depth);
        let mut index = 0;
        while index < events.len() {
            if !matches!(events[index], Event::Start(Tag::Item)) {
                index += 1;
                continue;
            }
            let (inner, used) = take_item(&events[index + 1..]);
            index += used + 2;

            // A task marker belongs on the item's own line, before its text.
            //
            // Only the item's *own leading* markers are lifted out. Filtering the
            // whole item would also take the markers of any list nested inside
            // it, and the nested items would then render with no checkbox at all
            // — the same class of silent loss as a truncated item.
            let mut done = None;
            let mut seen_content = false;
            let content: Vec<Event<'_>> = inner
                .iter()
                .filter(|event| match event {
                    Event::TaskListMarker(checked) if !seen_content => {
                        done = done.or(Some(*checked));
                        false
                    }
                    _ => {
                        seen_content = true;
                        true
                    }
                })
                .cloned()
                .collect();

            // The item's own blocks are rendered one level deeper, which is what
            // puts a list nested inside this item at the next column.
            let mut body = String::new();
            self.depth = depth + 1;
            self.blocks(&content, &mut body);
            self.depth = depth;

            // Blank lines are dropped inside an item: Typst reads a blank line
            // as the end of the item, so a loose markdown list would otherwise
            // come out as several one-line lists.
            let mut lines = body.lines().filter(|line| !line.trim().is_empty());
            // The first line carries the marker, so its own indent is replaced
            // by `indent` plus the two columns the marker takes.
            out.push_str(&indent);
            out.push(marker);
            out.push(' ');
            if let Some(done) = done {
                out.push_str(checkbox(done));
                out.push(' ');
            }
            out.push_str(lines.next().unwrap_or("").trim_start());
            out.push('\n');
            // Continuation lines are emitted **verbatim**, indentation included.
            // They were rendered one level deeper, which lands them exactly two
            // columns past the marker — where Typst needs them to be — and
            // re-indenting or trimming them here would flatten the nesting.
            for line in lines {
                out.push_str(line);
                out.push('\n');
            }
        }
        out.push('\n');
    }

    /// One `#table(...)` call.
    ///
    /// `stroke` is set because a Typst table has no lines by default, and a
    /// borderless grid of numbers does not read as a table.
    fn table(&mut self, events: &[Event<'_>], out: &mut String) {
        let mut rows: Vec<Vec<String>> = Vec::new();
        let mut row: Vec<String> = Vec::new();
        // GFM always emits a head, so the first row is the header unless the
        // document had none at all.
        let mut header = false;
        let mut cell: Option<String> = None;

        for event in events {
            match event {
                // The header's cells arrive without a `TableRow` around them,
                // so the head row is pushed when the head closes rather than on
                // a row end. Without this the header row is dropped and the
                // first body row is typeset as the header.
                Event::Start(Tag::TableHead) => {
                    header = true;
                    row.clear();
                }
                Event::End(TagEnd::TableHead) => rows.push(std::mem::take(&mut row)),
                Event::Start(Tag::TableRow) => row.clear(),
                Event::End(TagEnd::TableRow) => rows.push(std::mem::take(&mut row)),
                Event::Start(Tag::TableCell) => cell = Some(String::new()),
                Event::End(TagEnd::TableCell) => {
                    if let Some(text) = cell.take() {
                        row.push(text);
                    }
                }
                other => {
                    if let Some(text) = cell.as_mut() {
                        self.inline_one(other, text);
                    }
                }
            }
        }

        let columns = rows.iter().map(Vec::len).max().unwrap_or(1).max(1);
        out.push_str("#table(\n");
        out.push_str(&format!("  columns: {columns},\n"));
        out.push_str("  stroke: 0.5pt,\n");
        for (index, cells) in rows.iter().enumerate() {
            // Cells are content blocks, so the escaped markup goes in as
            // written and a `]` in the document cannot close one.
            let list = cells
                .iter()
                .map(|cell| format!("[{}]", cell.replace('\n', " ")))
                .collect::<Vec<_>>()
                .join(", ");
            if header && index == 0 {
                out.push_str(&format!("  table.header({list}),\n"));
            } else {
                out.push_str(&format!("  {list},\n"));
            }
        }
        out.push_str(")\n\n");
    }

    /// Render the inline events of one block.
    fn inline(&mut self, events: &[Event<'_>], out: &mut String) {
        // Merged first: `pulldown-cmark` splits one paragraph into several
        // `Text` events wherever markdown syntax *might* start — a lone `_`, a
        // `[`, an escaped `\\`. A math span like `$\sum_{i=0}^{n}$` is split
        // across three of them, and split per event it is not a math span at
        // all: the opening `$` ends up in one event and the closing `$` in
        // another, so the formula is typeset as escaped prose. Adjacent text
        // events are contiguous in the source, so merging them restores the
        // span without changing what the document said.
        for event in coalesce_text(events) {
            self.inline_one(&event, out);
        }
    }

    fn inline_one(&mut self, event: &Event<'_>, out: &mut String) {
        match event {
            // A text node inside an image that was emitted: the alt text has
            // already served as that image's content, so it must not appear a
            // second time.
            Event::Text(text) if self.suppress_image_text > 0 => {}
            Event::Text(text) => self.text(text, out),
            Event::Code(code) => out.push_str(&inline_code(code)),
            Event::SoftBreak => out.push('\n'),
            Event::HardBreak => out.push_str("\\\n"),
            Event::Start(Tag::Emphasis) => out.push('_'),
            Event::End(TagEnd::Emphasis) => out.push('_'),
            Event::Start(Tag::Strong) => out.push('*'),
            Event::End(TagEnd::Strong) => out.push('*'),
            Event::Start(Tag::Strikethrough) => out.push_str("#strike["),
            Event::End(TagEnd::Strikethrough) => out.push(']'),
            Event::Start(Tag::Link { dest_url, .. }) => {
                let safe = is_safe_url(dest_url);
                if let Some(url) = safe.then(|| quote_string(dest_url.as_ref())) {
                    out.push_str(&format!("#link({url})["));
                }
                self.link_stack.push(safe);
            }
            Event::End(TagEnd::Link) => {
                // Only close a bracket we opened. A dropped wrapper keeps its
                // text and nothing else, so the `]` has to follow the decision.
                if self.link_stack.pop().unwrap_or(false) {
                    out.push(']');
                }
            }
            Event::Start(Tag::Image { dest_url, .. }) => {
                // A remote image cannot work: the compiler has no network and a
                // `data:` URL is not an image to it either. The alt text is the
                // useful part of a broken image anyway, so it is left in place.
                let local = is_safe_url(dest_url)
                    && !dest_url.contains("://")
                    && !dest_url.starts_with("data:");
                if local {
                    out.push_str(&format!(
                        "#image({})",
                        quote_string(&image_path(dest_url.as_ref()))
                    ));
                    self.suppress_image_text += 1;
                }
            }
            Event::End(TagEnd::Image) => {
                if self.suppress_image_text > 0 {
                    self.suppress_image_text -= 1;
                }
            }
            Event::FootnoteReference(label) => {
                // Cloned rather than borrowed: rendering the body needs
                // `&mut self`, and the `in_footnote` flag is what stops a
                // definition that refers to itself from recursing forever.
                let body = if self.in_footnote {
                    None
                } else {
                    self.footnotes.get(label.as_ref()).cloned()
                };
                match body {
                    // Typst places a footnote at the foot of the page it is
                    // referenced from, which is what `#footnote` is for.
                    Some(body) => {
                        // The body is block content, so it is rendered as blocks
                        // and then trimmed: `#footnote[…]\\n\\n` would put the
                        // closing bracket on a line of its own inside the
                        // content block, which the compiler reads as content
                        // rather than as the end of the call.
                        let mut rendered = String::new();
                        self.in_footnote = true;
                        self.blocks(&parse(&body), &mut rendered);
                        self.in_footnote = false;
                        out.push_str("#footnote[");
                        out.push_str(rendered.trim_matches('\n'));
                        out.push(']');
                    }
                    // Undefined, or a reference inside a footnote body: show the
                    // label rather than losing the marker.
                    None => out.push_str(&escape_text(&format!("[^{label}]"))),
                }
            }
            // Raw HTML from the document: dropped, like in the HTML renderer.
            Event::Html(_) | Event::InlineHtml(_) => {}
            Event::Start(Tag::HtmlBlock) | Event::End(TagEnd::HtmlBlock) => {}
            // Block-level markers can reach the inline pass from inside a footnote
            // body. Dropping them is the whole treatment: recursing into the
            // same event would never terminate.
            _ => {}
        }
    }

    /// Document text, with math expanded by the shared splitter.
    ///
    /// Math goes through [`split_math`], the same detector the preview uses, so
    /// `$5 and $10` stays prose in the PDF exactly as it stays prose on screen.
    ///
    /// The TeX is then *translated* rather than passed through: Typst has no
    /// `\frac` and no `\sum`, and a single untranslated formula fails the whole
    /// compilation. See [`typst_math`] for the measured mapping.
    fn text(&mut self, text: &str, out: &mut String) {
        for piece in split_math(text) {
            match piece {
                MathPiece::Text(t) => out.push_str(&escape_text(&t)),
                MathPiece::Inline(tex) => {
                    out.push('$');
                    out.push_str(tex_to_typst(&tex).trim());
                    out.push('$');
                }
                MathPiece::Display(tex) => {
                    // A display formula gets a paragraph of its own, which is how
                    // Typst lays it out centred — and an `align`, which KaTeX
                    // spans over several rows, becomes several paragraphs.
                    for block in tex_to_typst_blocks(&tex) {
                        out.push_str("\n\n$ ");
                        out.push_str(block.trim());
                        out.push_str(" $\n\n");
                    }
                }
            }
        }
    }
}

/// The info string of a fenced code block, if it has one.
fn code_info<'a>(kind: &'a pulldown_cmark::CodeBlockKind<'a>) -> Option<&'a str> {
    match kind {
        pulldown_cmark::CodeBlockKind::Fenced(info) => Some(info.as_ref()),
        pulldown_cmark::CodeBlockKind::Indented => None,
    }
}

/// Merge runs of adjacent `Text` events.
///
/// The markdown parser emits one `Text` event per stretch it did not have to
/// break for syntax: `$\sum_{i=0}^{n}$` arrives as `$\sum`, `_`,
/// `{i=0}^{n}$`. Merging is safe because two adjacent text events are adjacent
/// in the source, and it is what lets a math span straddling one of those breaks
/// be recognised as a span.
fn coalesce_text<'a>(events: &'a [Event<'a>]) -> Vec<Event<'a>> {
    let mut out: Vec<Event<'a>> = Vec::with_capacity(events.len());
    for event in events {
        match (out.last_mut(), event) {
            (Some(Event::Text(previous)), Event::Text(current)) => {
                // `CowStr` has no `to_mut`, and an owned `String` is the only
                // shape that can grow, so the merged pair becomes one.
                let mut merged = String::new();
                merged.push_str(previous);
                merged.push_str(current);
                *previous = CowStr::from(merged);
            }
            _ => out.push(event.clone()),
        }
    }
    out
}

/// Collect the events up to, but not including, the first one matching `stop`.
fn take_until<'a>(
    events: &'a [Event<'a>],
    stop: impl Fn(&Event<'a>) -> bool,
) -> (Vec<Event<'a>>, usize) {
    let mut out = Vec::new();
    for (index, event) in events.iter().enumerate() {
        if stop(event) {
            return (out, index);
        }
        out.push(event.clone());
    }
    (out, events.len())
}

/// Collect the events of a list or a list item, stopping at its *matching* end.
///
/// A plain [`take_until`] is wrong for both, and wrong silently: a nested list
/// carries its own `End(List)` and `End(Item)`, so the outer one would be cut
/// short at the inner one. For a list that leaves the outer items to be picked
/// up by the enclosing walk at the wrong indent; for an item it swallows the
/// nested list whole and takes the nested item's `TaskListMarker` for its own.
///
/// So the depth of open lists is tracked, and only a terminator at depth zero
/// ends the construct.
fn take_nesting<'a>(
    events: &'a [Event<'a>],
    start: impl Fn(&Event<'a>) -> bool,
    end: impl Fn(&Event<'a>) -> bool,
) -> (Vec<Event<'a>>, usize) {
    let mut out = Vec::new();
    let mut depth = 0usize;
    for (index, event) in events.iter().enumerate() {
        if depth == 0 && end(event) {
            return (out, index);
        }
        if start(event) {
            depth += 1;
        } else if end(event) {
            depth = depth.saturating_sub(1);
        }
        out.push(event.clone());
    }
    (out, events.len())
}

/// One list's events, stopping at its matching `End(List)`.
fn take_list<'a>(events: &'a [Event<'a>]) -> (Vec<Event<'a>>, usize) {
    take_nesting(
        events,
        |e| matches!(e, Event::Start(Tag::List(_))),
        |e| matches!(e, Event::End(TagEnd::List(_))),
    )
}

/// One list item's events, stopping at its matching `End(Item)`.
fn take_item<'a>(events: &'a [Event<'a>]) -> (Vec<Event<'a>>, usize) {
    take_nesting(
        events,
        |e| matches!(e, Event::Start(Tag::Item)),
        |e| matches!(e, Event::End(TagEnd::Item)),
    )
}

/// Render the footnote definitions, keyed by label.
///
/// Separated from the main pass because a reference precedes its definition in
/// ordinary markdown, and the reference is where `#footnote` has to be emitted.
fn collect_footnotes(events: &[Event<'_>]) -> HashMap<String, String> {
    let mut out = HashMap::new();
    let mut index = 0;
    while index < events.len() {
        let Event::Start(Tag::FootnoteDefinition(label)) = &events[index] else {
            index += 1;
            continue;
        };
        let (inner, used) = take_until(&events[index + 1..], |e| {
            matches!(e, Event::End(TagEnd::FootnoteDefinition))
        });
        let mut writer = Writer {
            link_stack: Vec::new(),
            suppress_image_text: 0,
            footnotes: HashMap::new(),
            in_footnote: false,
            depth: 0,
            quote_depth: 0,
        };
        let mut body = String::new();
        writer.blocks(&inner, &mut body);
        out.insert(label.to_string(), body.trim_matches('\n').to_string());
        index += used + 2;
    }
    out
}

/// Parse `text` with the same options the rest of the app uses.
fn parse(text: &str) -> Vec<Event<'_>> {
    Parser::new_ext(text, parser_options()).collect()
}

